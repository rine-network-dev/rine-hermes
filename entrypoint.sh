#!/usr/bin/env bash
# Idempotent rig bootstrap for the contained hermes-rine test rig.
#
# Ensures the named-volume venv at $VENV holds:
#   - Hermes Agent (editable, from /opt/hermes — makes `hermes` CLI + gateway/tools/
#     hermes_cli/plugins importable)
#   - the bind-mounted local rine-sdk (editable — unreleased fixes)
#   - the bind-mounted hermes-rine[dev] (editable — the plugin under test + pytest/respx/...)
# Then writes ~/.hermes/{config.yaml,.env} (Together AI via the OpenAI-compatible custom
# provider) if absent, and exec's whatever command compose/`run` passed.
#
# The venv + Hermes' heavy dep tree live on a named volume, so the (slow) first install is
# cached for every later run and never touches the host.
set -euo pipefail

VENV="${VENV:-/opt/venv}"
MARKER="$VENV/.rig-installed"
HERMES_HOME="${HERMES_HOME:-/root/.hermes}"

if [ ! -f "$MARKER" ]; then
  echo ">>> [rig] bootstrapping venv at $VENV (first run installs Hermes + deps; slow, 2-6 min)" >&2
  UV="$(command -v uv)"
  "$UV" venv --clear --python 3.11 "$VENV"
  # `rine` MUST be the bind-mounted local SDK installed EDITABLE, so the rig always runs the
  # CURRENT SDK source and an unreleased SDK change can actually fail these tests. The local
  # path satisfies hermes-rine's `rine>=…` floor, so nothing is fetched from PyPI.
  # Three ways to silently lose editability — none may be reintroduced, because the venv
  # lives on a named volume and a non-editable install freezes an SDK snapshot for the life
  # of that volume:
  #   1. `--override "rine @ file:///work/rine-sdk"` — an override REPLACES the whole `rine`
  #      requirement, discarding both the editable flag AND the extra marker. MEASURED: rine
  #      installed non-editable with no eth-account, breaking every signing payer test.
  #   2. `-e "/work/rine-sdk[payments]"` — uv drops editability when a path carries extras.
  #   3. installing the SDK and hermes-rine in ONE `uv pip install` — hermes-rine[dev]
  #      requires `rine>=…`, and that dependency edge outranks the sibling `-e`, so rine is
  #      copied.
  # Hence separate steps: pin the SDK editable first (NO extra on the path), then Hermes and
  # hermes-rine[dev] find `rine` already satisfied and leave it alone. eth-account (x402
  # EIP-3009 signing for `rine_pay` / gateway auto-pay) comes from hermes-rine's own `dev`
  # extra, which lists it directly — so the SDK path never needs an extra. If local rine-sdk
  # ever falls below the floor the correct fix is to bump the SDK version, not mask it.
  # rine-mls (rine's compiled MLS + ML-KEM core) comes from the prebuilt wheelhouse
  # mounted at /work/wheels, never from source: the SDK's `[tool.uv.sources]` points it
  # at a crate, and building that crate needs a Rust toolchain no rig image carries.
  # `--no-index` is what proves the wheel came from there and not from PyPI, where
  # rine-mls is not published yet.
  "$UV" pip install --python "$VENV/bin/python" \
    --no-index --find-links /work/wheels rine-mls
  # ...so this install ignores that one source and takes the wheel above as satisfying
  # the SDK's `rine-mls` dependency. Every other source mapping still applies.
  "$UV" pip install --python "$VENV/bin/python" --no-sources-package rine-mls \
    -e /work/rine-sdk
  "$UV" pip install --python "$VENV/bin/python" \
    -e /opt/hermes \
    -e "/work/rine-hermes[dev]"
  touch "$MARKER"
  echo ">>> [rig] bootstrap complete" >&2
fi

# ---- Hermes config: Together AI via the OpenAI-compatible `custom` provider ----------
mkdir -p "$HERMES_HOME"
MODEL="${RINE_E2E_MODEL:-meta-llama/Llama-3.3-70B-Instruct-Turbo}"
BASE_URL="${RINE_E2E_BASE_URL:-https://api.together.xyz/v1}"

if [ ! -f "$HERMES_HOME/config.yaml" ]; then
  echo ">>> [rig] writing $HERMES_HOME/config.yaml (model=$MODEL)" >&2
  cat > "$HERMES_HOME/config.yaml" <<YAML
# Generated by the hermes-rine rig (entrypoint.sh). Together AI, OpenAI-compatible.
model:
  default: "$MODEL"
  provider: "custom"
  base_url: "$BASE_URL"
  context_length: 131072   # >= MINIMUM_CONTEXT_LENGTH (64k); pinned so the gate is deterministic
# Surface the rine toolset in CLI sessions (the plugin registers toolset "rine").
platform_toolsets:
  cli: [terminal, file, skills, todo, rine]
# Enable the rine plugin. \`hermes plugins enable rine --no-allow-tool-override\` writes
# this same key and works for a pip entry-point plugin; the rig writes the key directly
# because the config file is generated here in one piece anyway, and a second process
# round-trip would only add a way for the bootstrap to fail.
plugins:
  enabled: [rine]
YAML
fi

# Together key: Hermes derives the env var from the provider host (api.together.xyz ->
# TOGETHER_API_KEY). We persist it to ~/.hermes/.env (the documented mechanism) and keep
# it in the process env (compose env_file). OPENAI_API_KEY is set as a belt-and-braces
# fallback for the generic OpenAI-compatible client path.
if [ -n "${TOGETHER_API_KEY:-}" ] && [ ! -f "$HERMES_HOME/.env" ]; then
  echo ">>> [rig] writing $HERMES_HOME/.env (TOGETHER_API_KEY)" >&2
  {
    echo "TOGETHER_API_KEY=${TOGETHER_API_KEY}"
    echo "OPENAI_API_KEY=${TOGETHER_API_KEY}"
  } > "$HERMES_HOME/.env"
  chmod 600 "$HERMES_HOME/.env"
fi

exec "$@"
